import { loadEnvFile } from 'node:process';
import { writeFileSync } from 'node:fs';
import { pg } from '@zutrade/db';
loadEnvFile('.env');
const pool = new pg.Pool({ connectionString: process.env.MIGRATION_DATABASE_URL });
const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const tableVar = (s) => camel(s) + 'InApp';
const q = JSON.stringify;
try {
  const columns = (
    await pool.query(`SELECT c.relname AS tab,a.attname AS col,format_type(a.atttypid,a.atttypmod) AS type,a.attnotnull AS required,a.attidentity AS identity,pg_get_expr(d.adbin,d.adrelid) AS def
    FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace JOIN pg_attribute a ON a.attrelid=c.oid LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum WHERE n.nspname='app' AND c.relkind='r' AND a.attnum>0 AND NOT a.attisdropped ORDER BY c.relname,a.attnum`)
  ).rows;
  const constraints = (
    await pool.query(`SELECT c.relname AS tab,con.conname AS name,con.contype AS kind,pg_get_constraintdef(con.oid) AS definition,
    (SELECT json_agg(a.attname ORDER BY k.ord) FROM unnest(con.conkey) WITH ORDINALITY k(num,ord) JOIN pg_attribute a ON a.attrelid=con.conrelid AND a.attnum=k.num) AS cols,
    fc.relname AS target,(SELECT json_agg(a.attname ORDER BY k.ord) FROM unnest(con.confkey) WITH ORDINALITY k(num,ord) JOIN pg_attribute a ON a.attrelid=con.confrelid AND a.attnum=k.num) AS foreign_cols,
    pg_get_expr(con.conbin,con.conrelid) AS expression FROM pg_constraint con JOIN pg_class c ON c.oid=con.conrelid JOIN pg_namespace n ON n.oid=c.relnamespace LEFT JOIN pg_class fc ON fc.oid=con.confrelid WHERE n.nspname='app' ORDER BY c.relname,con.conname`)
  ).rows;
  let out = `// Generated by scripts/db-map.mjs from PostgreSQL catalogs, preserving ordered composite keys.\n// SQL migrations remain authoritative for RLS, triggers, indexes and deferred semantics. Never schema-push.\nimport {pgSchema,uuid,text,timestamp,bigint,jsonb,boolean,integer,numeric,smallint,date,foreignKey,unique,primaryKey,check,type PgTableExtraConfigValue} from 'drizzle-orm/pg-core';\nimport {sql} from 'drizzle-orm';\nexport const app=pgSchema('app');\n`;
  for (const table of [...new Set(columns.map((c) => c.tab))]) {
    const constraintsForTable = constraints.filter((c) => c.tab === table);
    out += `\nexport const ${tableVar(table)}=app.table(${q(table)},{\n`;
    for (const col of columns.filter((c) => c.tab === table)) {
      let type;
      const arg = q(col.col);
      if (col.type === 'timestamp with time zone')
        type = `timestamp(${arg},{withTimezone:true,mode:'string'})`;
      else if (col.type === 'bigint') type = `bigint(${arg},{mode:'bigint'})`;
      else if (col.type.startsWith('numeric')) {
        const [, precision, scale] = col.type.match(/numeric\((\d+),(\d+)\)/) ?? [];
        type = precision
          ? `numeric(${arg},{precision:${precision},scale:${scale}})`
          : `numeric(${arg})`;
      } else if (
        ['uuid', 'text', 'jsonb', 'boolean', 'integer', 'smallint', 'date'].includes(col.type)
      )
        type = `${col.type}(${arg})`;
      else throw new Error(`Unsupported type ${col.type}`);
      if (col.required) type += '.notNull()';
      if (col.identity) type += '.generatedAlwaysAsIdentity()';
      else if (col.def) type += `.default(sql.raw(${q(col.def)}))`;
      out += `${camel(col.col)}:${type},\n`;
    }
    out += '},(table):PgTableExtraConfigValue[]=>[\n';
    for (const c of constraintsForTable) {
      const cols = (c.cols ?? []).map((x) => 'table.' + camel(x)).join(',');
      if (c.kind === 'p') out += `primaryKey({name:${q(c.name)},columns:[${cols}]}),\n`;
      if (c.kind === 'u')
        out += `unique(${q(c.name)}).on(${cols})${c.definition.includes('NULLS NOT DISTINCT') ? '.nullsNotDistinct()' : ''},\n`;
      if (c.kind === 'f')
        out += `foreignKey({name:${q(c.name)},columns:[${cols}],foreignColumns:[${c.foreign_cols.map((x) => tableVar(c.target) + '.' + camel(x)).join(',')}]}),\n`;
      if (c.kind === 'c') out += `check(${q(c.name)},sql.raw(${q(c.expression)})),\n`;
    }
    out += ']);\n';
  }
  writeFileSync('packages/db/src/schema.ts', out);
  writeFileSync(
    process.env.CATALOG_EVIDENCE_PATH ?? 'docs/build/evidence/a1/catalog-mapping.json',
    JSON.stringify(
      {
        tables: [...new Set(columns.map((c) => c.tab))].length,
        columns: columns.length,
        foreignKeys: constraints.filter((c) => c.kind === 'f').length,
        compositeForeignKeys: constraints.filter((c) => c.kind === 'f' && c.cols.length > 1).length,
        checks: constraints.filter((c) => c.kind === 'c').length,
      },
      null,
      2,
    ) + '\n',
  );
  console.log('Catalog mapping generated for all business tables; no database mutation.');
} finally {
  await pool.end();
}
